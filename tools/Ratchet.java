import java.io.IOException;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import javax.xml.parsers.DocumentBuilderFactory;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;
import org.xml.sax.InputSource;

/**
 * The ratchet: existing problems may stay, new ones may not, and nobody loosens a gate quietly.
 *
 * <pre>
 *   java tools/Ratchet.java baseline     rewrite config/baseline from the reports in target/
 *   java tools/Ratchet.java check REF    compare the working tree with git REF, exit 1 if looser
 * </pre>
 *
 * <p>Run through the verify script, not directly. No dependencies beyond the JDK, so it runs
 * anywhere the build runs. A commit in REF..HEAD whose message has a {@code Ratchet-Override:}
 * line turns failures into warnings: a human decision, visible in history and review.
 */
public final class Ratchet {

  static final String BASELINE = "config/baseline";
  static final String CHECKSTYLE_BASELINE = BASELINE + "/checkstyle-suppressions.xml";
  static final String PMD_BASELINE = BASELINE + "/pmd-exclusions.properties";
  static final String CPD_BASELINE = BASELINE + "/cpd-exclusions.txt";
  static final String ARCHUNIT_STORE = BASELINE + "/archunit";
  static final String POM = "pom.xml";
  static final String CHECKSTYLE_CONFIG = "config/checkstyle/checkstyle.xml";
  static final String PMD_RULESET = "config/pmd/ruleset.xml";

  /** Markers that switch a check off in source code. Their count may not grow. */
  static final List<String> SUPPRESSION_MARKERS =
      List.of("@SuppressWarnings", "NOPMD", "CHECKSTYLE:OFF", "@Disabled", "@ArchIgnore");

  // No double dash: this text also goes into an XML comment.
  static final String HEADER = "Generated by the verify script, baseline option. May shrink, never grow.";

  public static void main(String[] args) throws Exception {
    if (args.length == 1 && args[0].equals("baseline")) {
      writeBaseline();
    } else if (args.length == 2 && args[0].equals("check")) {
      System.exit(check(args[1]));
    } else {
      System.err.println("usage: java tools/Ratchet.java baseline | check <git-ref>");
      System.exit(2);
    }
  }

  // ---------------------------------------------------------------- baseline

  static void writeBaseline() throws Exception {
    Files.createDirectories(Path.of(BASELINE));
    writeCheckstyleBaseline();
    writePmdBaseline();
    writeCpdBaseline();
  }

  static void writeCheckstyleBaseline() throws Exception {
    Set<String> lines = new TreeSet<>();
    Path report = Path.of("target/checkstyle-result.xml");
    if (Files.exists(report)) {
      Document doc = parse(Files.readString(report));
      for (Element file : elements(doc.getElementsByTagName("file"))) {
        String path = relative(file.getAttribute("name"));
        for (Element error : elements(file.getElementsByTagName("error"))) {
          lines.add(
              "  <suppress files=\"%s$\" checks=\"%s\"/>"
                  .formatted(path.replace(".", "\\."), checkName(error.getAttribute("source"))));
        }
      }
    }
    String body =
        """
        <?xml version="1.0"?>
        <!DOCTYPE suppressions PUBLIC
            "-//Checkstyle//DTD SuppressionFilter Configuration 1.2//EN"
            "https://checkstyle.org/dtds/suppressions_1_2.dtd">
        <!-- %s -->
        <suppressions>
        %s</suppressions>
        """
            .formatted(HEADER, lines.stream().map(l -> l + "\n").reduce("", String::concat));
    write(CHECKSTYLE_BASELINE, body, lines.size());
  }

  static void writePmdBaseline() throws Exception {
    Map<String, Set<String>> rulesPerClass = new TreeMap<>();
    Path report = Path.of("target/pmd.xml");
    if (Files.exists(report)) {
      Document doc = parse(Files.readString(report));
      for (Element file : elements(doc.getElementsByTagName("file"))) {
        for (Element v : elements(file.getElementsByTagName("violation"))) {
          String type =
              v.getAttribute("class").isEmpty()
                  ? className(file.getAttribute("name"))
                  : v.getAttribute("package") + "." + v.getAttribute("class");
          rulesPerClass.computeIfAbsent(type, k -> new TreeSet<>()).add(v.getAttribute("rule"));
        }
      }
    }
    StringBuilder body = new StringBuilder("# " + HEADER + "\n");
    rulesPerClass.forEach((type, rules) -> body.append(type).append('=')
        .append(String.join(",", rules)).append('\n'));
    write(PMD_BASELINE, body.toString(), rulesPerClass.values().stream().mapToInt(Set::size).sum());
  }

  static void writeCpdBaseline() throws Exception {
    Set<String> lines = new TreeSet<>();
    Path report = Path.of("target/cpd.xml");
    if (Files.exists(report)) {
      Document doc = parse(Files.readString(report));
      for (Element dup : elements(doc.getElementsByTagName("duplication"))) {
        Set<String> types = new TreeSet<>();
        for (Element file : elements(dup.getElementsByTagName("file"))) {
          types.add(className(file.getAttribute("path")));
        }
        lines.add(String.join(",", types));
      }
    }
    StringBuilder body = new StringBuilder("# " + HEADER + "\n");
    lines.forEach(l -> body.append(l).append('\n'));
    write(CPD_BASELINE, body.toString(), lines.size());
  }

  static void write(String path, String content, int entries) throws IOException {
    Files.writeString(Path.of(path), content);
    System.out.println("  " + path + ": " + entries + " entries");
  }

  // ---------------------------------------------------------------- check

  static int check(String base) throws Exception {
    List<String> problems = new ArrayList<>();
    checkBaselineDoesNotGrow(base, problems);
    checkPomThresholds(base, problems);
    checkCheckstyleLimits(base, problems);
    checkPmdRules(base, problems);
    checkErrorProneFlags(base, problems);
    checkSuppressionMarkers(base, problems);
    checkArchitectureConstants(base, problems);
    if (problems.isEmpty()) {
      return 0;
    }
    boolean overridden = hasOverride(base);
    String prefix = overridden ? "RATCHET (overridden): " : "RATCHET: ";
    problems.stream().limit(40).forEach(p -> System.out.println(prefix + p));
    if (problems.size() > 40) {
      System.out.println(prefix + "... and " + (problems.size() - 40) + " more");
    }
    if (overridden) {
      return 0;
    }
    System.out.println(
        "HINT: a gate got looser than on " + base + ". Fix the new problem instead of recording"
            + " it; never raise a limit or lower a minimum. If a human decided otherwise, add a"
            + " 'Ratchet-Override: <reason>' line to the commit message.");
    return 1;
  }

  static void checkBaselineDoesNotGrow(String base, List<String> problems) throws Exception {
    if (new Git(base).files(BASELINE).isEmpty()) {
      return; // adopting the ratchet: the first baseline is the starting point
    }
    Set<String> added = new TreeSet<>(baselineEntries(this_()));
    added.removeAll(baselineEntries(new Git(base)));
    added.forEach(e -> problems.add("new baseline entry " + e));
  }

  /** Every recorded violation, as one comparable string. */
  static Set<String> baselineEntries(Git git) throws Exception {
    Set<String> entries = new TreeSet<>();
    for (String line : git.lines(CHECKSTYLE_BASELINE)) {
      if (line.trim().startsWith("<suppress ")) {
        entries.add("(checkstyle) " + line.trim());
      }
    }
    Properties pmd = new Properties();
    pmd.load(new StringReader(String.join("\n", git.lines(PMD_BASELINE))));
    for (String type : pmd.stringPropertyNames()) {
      for (String rule : pmd.getProperty(type).split(",")) {
        entries.add("(pmd) " + type + " " + rule.trim());
      }
    }
    for (String line : git.lines(CPD_BASELINE)) {
      if (!line.isBlank() && !line.startsWith("#")) {
        entries.add("(cpd) " + line.trim());
      }
    }
    for (String file : git.files(ARCHUNIT_STORE)) {
      if (!file.endsWith("stored.rules")) {
        String text = String.join("\n", git.lines(file)).replace("\\\n", "\n");
        for (String violation : text.split("\n(?! )")) {
          if (!violation.isBlank()) {
            entries.add("(archunit) " + violation.lines().findFirst().orElse("").trim());
          }
        }
      }
    }
    return entries;
  }

  /** pom properties named *.minimum may not drop, *.maximum may not rise. */
  static void checkPomThresholds(String base, List<String> problems) throws Exception {
    Map<String, String> before = pomProperties(String.join("\n", new Git(base).lines(POM)));
    Map<String, String> now = pomProperties(Files.readString(Path.of(POM)));
    compareLimits("pom.xml", before, now, problems);
  }

  static Map<String, String> pomProperties(String pom) {
    Map<String, String> limits = new TreeMap<>();
    Matcher m = Pattern.compile("<([\\w.-]+\\.(?:minimum|maximum))>([^<]*)</\\1>").matcher(pom);
    while (m.find()) {
      limits.put(m.group(1), m.group(2).trim());
    }
    return limits;
  }

  /** Checkstyle: a max* property may not rise, a module may not disappear. */
  static void checkCheckstyleLimits(String base, List<String> problems) throws Exception {
    Map<String, String> before = new TreeMap<>();
    Map<String, String> now = new TreeMap<>();
    String old = String.join("\n", new Git(base).lines(CHECKSTYLE_CONFIG));
    if (old.isBlank()) {
      return;
    }
    collectModules(parse(old).getDocumentElement(), "", before);
    collectModules(parse(Files.readString(Path.of(CHECKSTYLE_CONFIG))).getDocumentElement(), "",
        now);
    compareLimits(CHECKSTYLE_CONFIG, before, now, problems);
  }

  static void collectModules(Element module, String parent, Map<String, String> out) {
    String path = parent + "/" + module.getAttribute("name");
    out.put(path + ".module", "present");
    for (Node child = module.getFirstChild(); child != null; child = child.getNextSibling()) {
      if (child instanceof Element e && e.getTagName().equals("module")) {
        collectModules(e, path, out);
      } else if (child instanceof Element e && e.getTagName().equals("property")) {
        String name = e.getAttribute("name");
        if (name.toLowerCase().contains("max")) {
          out.put(path + "." + name + ".maximum", e.getAttribute("value"));
        }
      }
    }
  }

  static void compareLimits(
      String where, Map<String, String> before, Map<String, String> now, List<String> problems) {
    before.forEach(
        (key, old) -> {
          String current = now.get(key);
          if (current == null) {
            problems.add(where + ": " + key + " was removed");
          } else if (key.endsWith(".minimum") && number(current) < number(old)) {
            problems.add(where + ": " + key + " lowered from " + old + " to " + current);
          } else if (key.endsWith(".maximum") && number(current) > number(old)) {
            problems.add(where + ": " + key + " raised from " + old + " to " + current);
          }
        });
  }

  static void checkPmdRules(String base, List<String> problems) throws Exception {
    Set<String> removed = new TreeSet<>(matches(new Git(base).lines(PMD_RULESET), "ref=\"([^\"]+)\""));
    removed.removeAll(matches(this_().lines(PMD_RULESET), "ref=\"([^\"]+)\""));
    removed.forEach(r -> problems.add(PMD_RULESET + ": rule " + r + " was removed"));
  }

  static void checkErrorProneFlags(String base, List<String> problems) throws Exception {
    String flag = "(-Xep:\\w+:(?:OFF|WARN)|-XepDisableAllChecks|-XepDisableAllWarnings)";
    Set<String> added = new TreeSet<>(matches(this_().lines(POM), flag));
    added.removeAll(matches(new Git(base).lines(POM), flag));
    added.forEach(f -> problems.add("pom.xml: Error Prone check switched off with " + f));
  }

  static void checkSuppressionMarkers(String base, List<String> problems) throws Exception {
    for (String marker : SUPPRESSION_MARKERS) {
      int before = new Git(base).count(marker);
      int now = this_().count(marker);
      if (now > before) {
        problems.add(
            "'" + marker + "' in src/ went from " + before + " to " + now
                + " (grep -rn '" + marker + "' src)");
      }
    }
  }

  /** Limits written as constants in tests, e.g. ArchitectureTest.MAX_CLASSES_PER_PACKAGE. */
  static void checkArchitectureConstants(String base, List<String> problems) throws Exception {
    Map<String, String> before = new TreeMap<>();
    Map<String, String> now = new TreeMap<>();
    String constant = "static final int (MAX_\\w+) = (\\d+);";
    for (String file : run("git", "grep", "-l", "--untracked", "-E", constant, "--", "src")) {
      constants(new Git(base).lines(file), file, constant, before);
      constants(this_().lines(file), file, constant, now);
    }
    before.keySet().retainAll(now.keySet());
    compareLimits("tests", before, now, problems);
  }

  static void constants(List<String> lines, String file, String regex, Map<String, String> out) {
    Pattern p = Pattern.compile(regex);
    for (String line : lines) {
      Matcher m = p.matcher(line);
      if (m.find()) {
        out.put(file + " " + m.group(1) + ".maximum", m.group(2));
      }
    }
  }

  static boolean hasOverride(String base) throws Exception {
    return run("git", "log", "--format=%B", base + "..HEAD").stream()
        .anyMatch(l -> l.startsWith("Ratchet-Override:"));
  }

  // ---------------------------------------------------------------- helpers

  /** Reads files either from the working tree ({@code ref == null}) or from a git ref. */
  record Git(String ref) {
    List<String> lines(String path) throws Exception {
      if (ref == null) {
        Path p = Path.of(path);
        return Files.exists(p) ? Files.readAllLines(p) : List.of();
      }
      List<String> listed = run("git", "ls-tree", "--name-only", ref, "--", path);
      return listed.isEmpty() ? List.of() : run("git", "show", ref + ":" + path);
    }

    List<String> files(String dir) throws Exception {
      if (ref == null) {
        if (!Files.isDirectory(Path.of(dir))) {
          return List.of();
        }
        try (Stream<Path> walk = Files.walk(Path.of(dir))) {
          return walk.filter(Files::isRegularFile).map(p -> p.toString().replace('\\', '/'))
              .sorted().toList();
        }
      }
      return run("git", "ls-tree", "-r", "--name-only", ref, "--", dir);
    }

    /** Lines under src/ that contain the marker. */
    int count(String marker) throws Exception {
      List<String> perFile =
          ref == null
              ? run("git", "grep", "-c", "-F", "--untracked", "-e", marker, "--", "src")
              : run("git", "grep", "-c", "-F", "-e", marker, ref, "--", "src");
      return perFile.stream()
          .mapToInt(l -> Integer.parseInt(l.substring(l.lastIndexOf(':') + 1)))
          .sum();
    }
  }

  static Git this_() {
    return new Git(null);
  }

  static List<String> run(String... command) throws Exception {
    Process p = new ProcessBuilder(command).redirectErrorStream(false).start();
    String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    p.getErrorStream().readAllBytes();
    if (p.waitFor() != 0) {
      return List.of();
    }
    return out.lines().toList();
  }

  static Set<String> matches(List<String> lines, String regex) {
    Set<String> found = new TreeSet<>();
    Matcher m = Pattern.compile(regex).matcher(String.join("\n", lines));
    while (m.find()) {
      found.add(m.group(1));
    }
    return found;
  }

  static Document parse(String xml) throws Exception {
    DocumentBuilderFactory f = DocumentBuilderFactory.newInstance();
    f.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
    return f.newDocumentBuilder().parse(new InputSource(new StringReader(xml)));
  }

  static List<Element> elements(NodeList nodes) {
    List<Element> list = new ArrayList<>();
    for (int i = 0; i < nodes.getLength(); i++) {
      list.add((Element) nodes.item(i));
    }
    return list;
  }

  static String relative(String absolute) {
    String cwd = Path.of("").toAbsolutePath().toString().replace('\\', '/') + "/";
    String path = absolute.replace('\\', '/');
    return path.startsWith(cwd) ? path.substring(cwd.length()) : path;
  }

  /** src/main/java/com/example/Foo.java -> com.example.Foo */
  static String className(String path) {
    String p = relative(path);
    int root = p.indexOf("/java/");
    return (root < 0 ? p : p.substring(root + 6)).replaceAll("\\.java$", "").replace('/', '.');
  }

  /** com.puppycrawl.tools.checkstyle.checks.sizes.MethodLengthCheck -> MethodLength */
  static String checkName(String source) {
    return source.substring(source.lastIndexOf('.') + 1).replaceAll("Check$", "");
  }

  static double number(String value) {
    try {
      return Double.parseDouble(value);
    } catch (NumberFormatException e) {
      return Double.NaN;
    }
  }

  private Ratchet() {}
}
